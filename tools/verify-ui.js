async (page) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const checks = [];
  const check = (condition, label) => { if (!condition) throw new Error(label); checks.push(label); };
  await page.getByRole('button', {name:'添加中转',exact:true}).first().click();
  await page.getByRole('textbox', {name:'名称',exact:true}).fill('Aurora API');
  await page.getByRole('textbox', {name:'中转地址',exact:true}).fill('__UPSTREAM_URL__');
  await page.getByRole('textbox', {name:'分组名称 1',exact:true}).fill('日常使用');
  await page.getByRole('textbox', {name:'分组 Key 1',exact:true}).fill('key-a');
  await page.getByRole('button', {name:'添加 Key',exact:true}).click();
  await page.getByRole('textbox', {name:'分组名称 2',exact:true}).fill('备用通道');
  await page.getByRole('textbox', {name:'分组 Key 2',exact:true}).fill('key-b');
  check(!await page.locator('#relay-dialog').innerText().then(text => text.includes('余额')), '添加界面无余额配置');
  await page.getByRole('button', {name:'添加并获取模型',exact:true}).click();
  await page.getByRole('button', {name:'展开分组',exact:true}).waitFor();
  check(await page.locator('.group-row').count() === 0, '新增中转默认收起分组');
  await page.waitForFunction(() => document.querySelector('.relay-row .row-model-count')?.textContent.includes('7'));
  check(await page.locator('.relay-table-head').innerText().then(text => !text.includes('余额')), '中转列表没有余额列');
  check(!await page.locator('#page-relays').innerText().then(text => text.includes('首字')), '中转页不显示首字延迟');
  await page.screenshot({path:'output/playwright/16-v04-collapsed.png'});
  await page.getByRole('button', {name:'展开分组',exact:true}).click();
  await page.getByRole('button', {name:'刷新模型',exact:true}).click();
  await page.locator('.group-row .spinner').first().waitFor();
  const rows = await page.locator('.group-row').evaluateAll(rows => rows.map(row => ({height:row.getBoundingClientRect().height,spinners:[...row.querySelectorAll('.spinner')].map(el=>({width:el.getBoundingClientRect().width,height:el.getBoundingClientRect().height})),icons:[...row.querySelectorAll('svg')].map(el=>({width:el.getBoundingClientRect().width,fill:getComputedStyle(el).fill}))})));
  check(rows.every(row => row.height <= 64 && row.spinners.every(spinner => spinner.width===12 && spinner.height===12)), '模型加载圆环 12px，分组行高度正常');
  check(rows.every(row => row.icons.every(icon => icon.width<=20 && icon.fill==='none')), '图标尺寸与填充正常');
  check(await page.locator('#app-loading').isVisible(), '同步时显示细进度条');
  await page.screenshot({path:'output/playwright/17-v04-loading.png'});
  await page.waitForFunction(()=>document.querySelector('#app-loading').hidden);
  check(await page.locator('.spinner').count()===0, '同步完成后清理加载动画');
  await page.getByRole('button', {name:'管理 日常使用 的模型',exact:true}).click();
  await page.getByRole('switch', {name:'启用模型 gpt-test',exact:true}).waitFor();
  await page.getByRole('switch', {name:'启用模型 gpt-test',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="启用模型 gpt-test"]').getAttribute('aria-checked')==='false');
  checks.push('模型独立开关');
  await page.getByRole('textbox', {name:'搜索模型',exact:true}).fill('claude');
  check(await page.getByRole('switch', {name:'启用模型 claude-test',exact:true}).count()===1, '模型搜索');
  await page.getByRole('textbox', {name:'搜索模型',exact:true}).fill('');
  await page.getByRole('button', {name:'全部关闭',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#model-enabled-count').textContent==='已开启 0 / 7');
  checks.push('批量关闭模型');
  await page.getByRole('button', {name:'全部开启',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#model-enabled-count').textContent==='已开启 7 / 7');
  checks.push('批量开启模型');
  await page.getByRole('button', {name:'关闭模型面板',exact:true}).click();
  await page.getByRole('switch', {name:'启用分组 备用通道',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="启用分组 备用通道"]').getAttribute('aria-checked')==='false');
  checks.push('分组独立开关');
  await page.getByRole('switch', {name:'启用分组 备用通道',exact:true}).click();
  await page.getByRole('button', {name:'设置',exact:true}).click();
  await page.getByRole('textbox', {name:'接入 Key',exact:true}).fill('x');
  await page.getByRole('button', {name:'保存设置',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#settings-feedback').textContent.includes('保存'));
  checks.push('自定义短 Key 保存');
  await page.getByRole('textbox', {name:'接入 Key',exact:true}).fill('sk-local');
  await page.getByRole('button', {name:'保存设置',exact:true}).click();
  const response = await page.request.post(new URL('/v1/chat/completions',page.url()).href,{headers:{Authorization:'Bearer sk-local'},data:{model:'gpt-test',stream:true,messages:[{role:'user',content:'test'}]}});
  check(response.ok(),'流式请求成功');
  await page.reload();
  await page.getByRole('button',{name:'展开分组',exact:true}).waitFor();
  check(await page.locator('.group-row').count()===0,'重载后分组默认收起');
  await page.getByRole('button',{name:'用量',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#request-rows tr td:nth-child(3)')?.textContent.includes('ms'));
  check(await page.locator('.request-table th').allTextContents().then(values=>values.includes('首字延迟')),'首字延迟保留在最近请求');
  await page.screenshot({path:'output/playwright/18-v04-usage.png'});
  await page.setViewportSize({width:960,height:660});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'最小窗口没有横向溢出');
  check(errors.length===0,'页面无 JavaScript 错误');
  await page.setViewportSize({width:1240,height:810});
  return {checks};
}
